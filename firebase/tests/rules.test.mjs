import {readFileSync} from 'node:fs';
import {before, after, test} from 'node:test';
import {initializeTestEnvironment, assertFails, assertSucceeds} from '@firebase/rules-unit-testing';
import {doc, getDoc, setDoc, updateDoc, serverTimestamp, collection, getDocs} from 'firebase/firestore';
let env;
before(async () => {
  env = await initializeTestEnvironment({projectId:'demo-elderly-safety',firestore:{rules:readFileSync('firestore.rules','utf8'),host:'127.0.0.1',port:8080}});
  await env.clearFirestore();
  await env.withSecurityRulesDisabled(async c => {
    const db=c.firestore();
    await setDoc(doc(db,'profiles/p1'),{displayName:'Test profile'});
    await setDoc(doc(db,'profiles/p1/caregivers/alice'),{role:'caregiver'});
    await setDoc(doc(db,'profiles/p1/caregivers/viewer'),{role:'viewer'});
    await setDoc(doc(db,'profiles/p1/alerts/a1'),{kind:'POSSIBLE_FALL',seenAt:null,seenBy:null,safeAt:null,safeBy:null});
    await setDoc(doc(db,'profiles/p1/status/current'),{posture:'STANDING'});
  });
});
after(async()=>{await env?.cleanup();});
const db = uid => env.authenticatedContext(uid).firestore();
test('anonymous cannot read profiles',async()=>assertFails(getDoc(doc(env.unauthenticatedContext().firestore(),'profiles/p1'))));
test('unlinked account cannot read profile',async()=>assertFails(getDoc(doc(db('bob'),'profiles/p1'))));
test('caregiver reads linked status',async()=>assertSucceeds(getDoc(doc(db('alice'),'profiles/p1/status/current'))));
test('cannot forge fall event',async()=>assertFails(setDoc(doc(db('alice'),'profiles/p1/events/fake'),{kind:'POSSIBLE_FALL'})));
test('cannot self grant membership',async()=>assertFails(setDoc(doc(db('bob'),'profiles/p1/caregivers/bob'),{role:'caregiver'})));
test('cannot alter trusted status',async()=>assertFails(updateDoc(doc(db('alice'),'profiles/p1/status/current'),{posture:'LYING'})));
test('seen acknowledgment is permitted',async()=>assertSucceeds(updateDoc(doc(db('alice'),'profiles/p1/alerts/a1'),{seenBy:'alice',seenAt:serverTimestamp()})));
test('safe confirmation is distinct',async()=>assertSucceeds(updateDoc(doc(db('alice'),'profiles/p1/alerts/a1'),{safeBy:'alice',safeAt:serverTimestamp()})));
test('viewer cannot acknowledge',async()=>assertFails(updateDoc(doc(db('viewer'),'profiles/p1/alerts/a1'),{seenBy:'viewer',seenAt:serverTimestamp()})));
test('cannot rewrite event kind while acknowledging',async()=>assertFails(updateDoc(doc(db('alice'),'profiles/p1/alerts/a1'),{kind:'NORMAL',seenBy:'alice',seenAt:serverTimestamp()})));
test('cannot impersonate another caregiver',async()=>assertFails(updateDoc(doc(db('alice'),'profiles/p1/alerts/a1'),{safeBy:'bob',safeAt:serverTimestamp()})));
test('cannot use client chosen acknowledgment time',async()=>assertFails(updateDoc(doc(db('alice'),'profiles/p1/alerts/a1'),{seenBy:'alice',seenAt:new Date(0)})));
test('own device registration allowed',async()=>assertSucceeds(setDoc(doc(db('alice'),'users/alice/devices/test'),{token:'a'.repeat(40),platform:'android',enabled:true,updatedAt:serverTimestamp()})));
test('other account cannot read tokens',async()=>assertFails(getDoc(doc(db('bob'),'users/alice/devices/test'))));
test('token extra fields rejected',async()=>assertFails(setDoc(doc(db('alice'),'users/alice/devices/extra'),{token:'a'.repeat(40),platform:'android',enabled:true,updatedAt:serverTimestamp(),admin:true})));
test('caregivers cannot enumerate tokens',async()=>assertFails(getDocs(collection(db('bob'),'users/alice/devices'))));
test('profile query forbidden; use own profile links',async()=>assertFails(getDocs(collection(db('alice'),'profiles'))));
